#!/usr/bin/env python3
"""Bundle runtime code and pin mirrored, checksummed model-data downloads."""

import argparse
import json
import re
from pathlib import Path

from extract_audio_context import sha256


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "revision", help="Git commit containing ml/assets, or LOCAL for development"
    )
    args = parser.parse_args()
    if args.revision != "LOCAL" and not re.fullmatch(r"[0-9a-f]{40}", args.revision):
        raise ValueError("expected full Git revision")
    assets = Path("ml/assets")
    manifest = json.loads((assets / "manifest.json").read_text())
    resources = {
        "spokoynoMLModel": "model.json",
        "spokoynoMLWeights": "weights.bin.b64",
        "spokoynoMLWasm": "tf.wasm.b64",
        "spokoynoMLSimd": "tf-simd.wasm.b64",
    }
    for name in [*resources.values(), "runtime.js"]:
        if sha256(assets / name) != manifest["resources"][name]:
            raise ValueError("assets changed since build")
    bases = [
        f"https://cdn.jsdelivr.net/gh/godlikedh/spokoyno@{args.revision}/ml/assets/",
        f"https://raw.githubusercontent.com/godlikedh/spokoyno/{args.revision}/ml/assets/",
    ]
    script = Path("spokoyno.user.js")
    source = script.read_text()
    source = re.sub(r"^// @(?:require|resource)\s+.*\n", "", source, flags=re.M)
    source = re.sub(
        r"  const ML_ASSET_BASES = .*?;",
        "  const ML_ASSET_BASES = " + json.dumps(bases) + ";",
        source,
        count=1,
        flags=re.S,
    )
    hashes = {n: manifest["resources"][f] for n, f in resources.items()}
    source = re.sub(
        r"  const ML_RESOURCE_HASHES = .*?;[^\n]*",
        "  const ML_RESOURCE_HASHES = " + json.dumps(hashes) + ";",
        source,
        count=1,
        flags=re.S,
    )
    bundle = (
        "  // ML_RUNTIME_BUNDLE_START\n"
        "  // Generated by research/pin_browser_ml.py from ml/assets/runtime.js.\n"
        "  // TensorFlow.js and YAMNet: Apache-2.0; see ml/assets/LICENSE-*.\n"
        "  // prettier-ignore\n"
        "  function spokoynoMLRuntime() {\n"
        + (assets / "runtime.js").read_text()
        + "\n    return { tf: globalThis.tf, ML: globalThis.SpokoynoML };\n"
        "  }\n"
        "  // ML_RUNTIME_BUNDLE_END\n"
    )
    source = re.sub(
        r"  // ML_RUNTIME_BUNDLE_START\n.*?  // ML_RUNTIME_BUNDLE_END\n",
        "",
        source,
        flags=re.S,
    )
    at = source.rfind("})();")
    if at < 0:
        raise ValueError("userscript closure not found")
    source = source[:at] + bundle + source[at:]
    script.write_text(source)


if __name__ == "__main__":
    main()
